    template<typename T>
    constexpr T&& forward(remove_reference_t<T> &arg) noexcept {
        return static_cast<T&&>(arg);
    }

    template<typename T>
    constexpr void swap(T &x, T &y) noexcept {
        T temp = kstd::move(x);
        x = kstd::move(y);
        y = kstd::move(temp);
    }

